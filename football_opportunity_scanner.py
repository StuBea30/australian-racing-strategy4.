"""Football Strategy 3.0: odds-based opportunity scanner, Telegram delivery, no betting.
Requires football_probabilities.json generated by football_model.py.
"""
import argparse
import json
import os
import re
import sys
from datetime import datetime, timedelta, timezone
from difflib import SequenceMatcher
from pathlib import Path
from zoneinfo import ZoneInfo

import requests

SPORTS = {'BL1':'soccer_germany_bundesliga','DED':'soccer_netherlands_eredivisie',
          'ELC':'soccer_efl_champ','SA':'soccer_italy_serie_a'}
BASE = 'https://api.the-odds-api.com/v4'
MARKETS = ['totals','btts','alternate_totals','draw_no_bet']
# The Odds API charges by market x region; keep the initial daily budget conservative.
DEFAULT_MAX_CREDITS = 12
ALIASES = {'bayern munich':'bayern','fc bayern munchen':'bayern',
           '1 fc koln':'koln','fc koln':'koln','cologne':'koln',
           'borussia dortmund':'dortmund','bvb':'dortmund',
           'inter milan':'inter','internazionale':'inter',
           'ac milan':'milan','psv eindhoven':'psv','ajax amsterdam':'ajax',
           'manchester united':'man united','manchester city':'man city'}

def norm(name):
    s = name.lower().replace('ü','u').replace('ö','o').replace('ä','a').replace('ß','ss')
    s = re.sub(r'[^a-z0-9 ]+', ' ', s)
    s = re.sub(r'\b(fc|afc|cf|sc|sv|bv|the|football|club)\b',' ',s)
    s = ' '.join(s.split())
    return ALIASES.get(s,s)

def match_score(a,b):
    a,b=norm(a),norm(b)
    if a==b: return 1.0
    if a in b or b in a: return 0.94 if min(len(a),len(b))>=5 else 0.0
    return SequenceMatcher(None,a,b).ratio()

def match_fixture(f, events):
    kick=datetime.fromisoformat(f['kickoff_utc'].replace('Z','+00:00'))
    candidates=[]
    for e in events:
        try: dt=datetime.fromisoformat(e['commence_time'].replace('Z','+00:00'))
        except (KeyError,ValueError): continue
        if abs((dt-kick).total_seconds())>4*3600: continue
        h=match_score(f['home'],e['home_team']); a=match_score(f['away'],e['away_team'])
        if min(h,a)>=0.83: candidates.append((min(h,a),e))
    candidates.sort(key=lambda x:x[0],reverse=True)
    if not candidates: return None
    if len(candidates)>1 and candidates[0][0]-candidates[1][0]<0.05: return None
    return candidates[0][1]

def fetch_odds(sport, key, market, region, timeout=25):
    r=requests.get(f'{BASE}/sports/{sport}/odds',params={
        'apiKey':key,'regions':region,'markets':market,'oddsFormat':'decimal'},timeout=timeout)
    remaining=r.headers.get('x-requests-remaining')
    used=r.headers.get('x-requests-used')
    if r.status_code!=200:
        return None, remaining, used, f'{market}: HTTP {r.status_code}: {r.text[:180]}'
    return r.json(),remaining,used,None

def extract_prices(event):
    """Yield (market_key, point, side, price, bookmaker, updated)."""
    for book in event.get('bookmakers',[]):
        for market in book.get('markets',[]):
            mk=market.get('key')
            for outcome in market.get('outcomes',[]):
                try: price=float(outcome['price'])
                except (KeyError,ValueError,TypeError): continue
                if price<=1: continue
                point=outcome.get('point')
                try: point=float(point) if point is not None else None
                except (ValueError,TypeError): continue
                yield mk,point,str(outcome.get('name','')),price,book.get('title','Unknown'),market.get('last_update',book.get('last_update','Unknown'))

def selection(f,event):
    m=f['markets']; choices=[]
    mapping={'over_2_5':('totals',2.5,'Over'),'under_2_5':('totals',2.5,'Under'),
             'over_3_5':('totals',3.5,'Over'),'under_3_5':('totals',3.5,'Under'),
             'btts_yes':('btts',None,'Yes'),'btts_no':('btts',None,'No'),
             'home_dnb':('draw_no_bet',None,event['home_team']),
             'away_dnb':('draw_no_bet',None,event['away_team'])}
    prices=list(extract_prices(event))
    for name,(mk,point,side) in mapping.items():
        offers=[]
        for key,p,who,price,book,updated in prices:
            if key not in ([mk,'alternate_totals'] if mk=='totals' else [mk]): continue
            if point is not None and (p is None or abs(p-point)>0.001): continue
            if point is None and p is not None: continue
            if (norm(who)==norm(side) if mk=='draw_no_bet' else who.lower()==side.lower()):
                offers.append((price,book,updated))
        # Two DISTINCT bookmakers must quote the specific selection.
        unique={b for _,b,_ in offers}
        if len(unique)<2: continue
        price,book,updated=max(offers,key=lambda x:x[0])
        if price<1.80: continue
        if mk=='draw_no_bet':
            p=m[name]['win']; lose=m[name]['lose']; push=m[name]['push']
            ev=p*(price-1)-lose
            edge=None
            qualifies=ev>0
        else:
            p=float(m[name]); push=0
            edge=p-1/price
            ev=p*price-1
            qualifies=edge>=0.05 and ev>0
        choices.append({'league':f['league'],'home':f['home'],'away':f['away'],
                        'kickoff_utc':f['kickoff_utc'],'market':name,'odds':price,
                        'bookmaker':book,'odds_updated':updated,'model_probability':p,
                        'push_probability':push,'edge':edge,'ev_per_unit':ev,
                        'qualifies':qualifies,'stake_gbp':5})
    return choices

def send_telegram(message,token,chat_id):
    r=requests.post(f'https://api.telegram.org/bot{token}/sendMessage',
                    json={'chat_id':chat_id,'text':message,'disable_web_page_preview':True},timeout=30)
    r.raise_for_status()
    if not r.json().get('ok'): raise RuntimeError('Telegram API did not confirm delivery')

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--forecasts',default='football_probabilities.json')
    ap.add_argument('--output',default='football_opportunities.json')
    ap.add_argument('--send',action='store_true')
    ap.add_argument('--region',default='uk')
    ap.add_argument('--max-credits',type=int,default=DEFAULT_MAX_CREDITS)
    args=ap.parse_args()
    key=os.environ.get('ODDS_API_KEY')
    if not key: sys.exit('ODDS_API_KEY missing')
    data=json.loads(Path(args.forecasts).read_text(encoding='utf-8'))
    now=datetime.now(timezone.utc)
    today=now.astimezone(ZoneInfo('Europe/London')).date()
    fixtures=[]
    for f in data['fixtures']:
        k=datetime.fromisoformat(f['kickoff_utc'].replace('Z','+00:00'))
        if k>now and k.astimezone(ZoneInfo('Europe/London')).date()==today:
            fixtures.append(f)
    # Only today's UK-local fixtures are eligible; no requests if there are none.
    league_codes=sorted({f['league'] for f in fixtures if f['league'] in SPORTS})
    errors=[]; quota=None; spent=0; events_by_league={}
    # Prioritize totals and BTTS. Additional markets only while safely inside credit cap.
    for code in league_codes:
        events_by_league[code]={}
    # Round-robin markets: all four leagues receive core coverage before optional markets.
    for market in MARKETS:
        for code in league_codes:
            if spent>=args.max_credits: break
            if quota is not None and quota<=args.max_credits:
                errors.append('Low monthly credit balance: stopped optional requests')
                break
            result,remaining,used,error=fetch_odds(SPORTS[code],key,market,args.region)
            if remaining is not None:
                try: quota=int(remaining)
                except ValueError: pass
            if error: errors.append(f'{code}: {error}')
            else:
                spent+=1
                for e in result:
                    eid=e['id']; target=events_by_league[code].setdefault(eid,{**e,'bookmakers':[]})
                    for b in e.get('bookmakers',[]):
                        existing=next((x for x in target['bookmakers'] if x.get('key')==b.get('key')),None)
                        if existing: existing['markets'].extend(b.get('markets',[]))
                        else: target['bookmakers'].append({**b,'markets':list(b.get('markets',[]))})
        if spent>=args.max_credits or (quota is not None and quota<=args.max_credits): break
    all_choices=[]; unmatched=[]
    for f in fixtures:
        e=match_fixture(f,list(events_by_league.get(f['league'],{}).values()))
        if e is None: unmatched.append(f"{f['home']} v {f['away']}")
        else: all_choices.extend(selection(f,e))
    eligible=sorted([x for x in all_choices if x['qualifies']],key=lambda x:x['ev_per_unit'],reverse=True)
    # Avoid correlated multiple markets in the same fixture; choose strongest one.
    top=[]; seen=set()
    for x in eligible:
        key=(x['league'],x['home'],x['away'])
        if key in seen: continue
        top.append(x);seen.add(key)
        if len(top)==3: break
    lines=[f'⚽ FOOTBALL STRATEGY 3.0 — {today:%d %b %Y}',
           f'Top qualifying bets: {len(top)} | £5 each']
    if not fixtures:
        lines.extend(['', 'No fixtures scheduled today in the four tracked leagues.', 'No bookmaker odds requests needed.'])
    elif top:
        for i,x in enumerate(top,1):
            when=datetime.fromisoformat(x['kickoff_utc']).astimezone(ZoneInfo('Europe/London'))
            label=x['market'].replace('_',' ').upper()
            lines.extend(['',f"{i}. {x['home']} v {x['away']} ({x['league']})",
                          f"{when:%H:%M} UK | {label}",
                          f"Odds {x['odds']:.2f} — {x['bookmaker']}",
                          f"Model {x['model_probability']:.1%}" + (f" | Edge +{x['edge']:.1%}" if x['edge'] is not None else f" | EV +{x['ev_per_unit']:.1%} per £1"),
                          f"Odds checked: {x['odds_updated']} | Stake £5"])
    elif errors or unmatched or not all_choices:
        lines.extend(['', 'SCAN INCOMPLETE — no verified qualifying bets.', 'Some fixtures or markets could not be fully checked; this is not a confirmed no-bet day.'])
    else:
        lines.extend(['', 'No qualifying bets found in the markets successfully checked.'])
    lines.extend(['',f'Fixtures scanned: {len(fixtures)} | Matched: {len(fixtures)-len(unmatched)}',
                  f'Quoted candidates (>=1.80, 2 bookmakers): {len(all_choices)}',
                  f'Odds requests: {spent} | Monthly credits remaining: {quota if quota is not None else "unknown"}'])
    if unmatched: lines.append(f'Unmatched fixtures: {len(unmatched)}')
    if errors: lines.append('Coverage/API warnings: '+ '; '.join(errors[:3]))
    if fixtures and spent == 0: lines.append('WARNING: No bookmaker odds requests were made.')
    lines.append('Selections are suggestions, not placed bets. Odds can change.')
    status=('no_fixtures_today' if not fixtures else 'incomplete' if errors or unmatched or not all_choices else 'checked')
    report={'status':status,'date_uk':str(today),'generated_utc':now.isoformat(),'fixtures_scanned':len(fixtures),
            'unmatched':unmatched,'errors':errors,'odds_requests':spent,'credits_remaining':quota,
            'top_three':top,'qualifying_count':len(eligible),'candidates':all_choices}
    Path(args.output).write_text(json.dumps(report,indent=2,allow_nan=False),encoding='utf-8')
    msg='\n'.join(lines)
    print(msg)
    if args.send:
        token=os.environ.get('TELEGRAM_BOT_TOKEN'); chat=os.environ.get('TELEGRAM_CHAT_ID')
        if not token or not chat: sys.exit('Telegram credentials missing; no message sent')
        send_telegram(msg,token,chat)
        print('Telegram delivery confirmed')

if __name__=='__main__': main()
